def fetch_all(force: bool = False) -> dict[str, Path]:
    _DEST_DIR.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for locale in _BASE_LOCALES:
        dest = _DEST_DIR / f"{locale}.json"
        if dest.exists() and not force:
            paths[locale] = dest
            continue
        response = requests.get(_URL_TEMPLATE.format(locale=locale), timeout=30)
        response.raise_for_status()
        dest.write_bytes(response.content)
        paths[locale] = dest
    return paths


if __name__ == "__main__":
    fetched = fetch_all()
    print(f"Fetched {len(fetched)} CLDR locale files -> {_DEST_DIR}")
