"""Downloads Unicode CLDR's per-locale "exemplar character" data — the standard, structured
source for "what letters does this language's orthography actually use" (e.g. French's main
set is "a à â æ b c ç d e é è ê ë ..."), used to populate LanguageProfile.writing_system.
scripts[].sample_glyphs (see pipeline/cldr_loader.py). Not an LLM guess: CLDR is Unicode's own
locale-data repository, already the de facto source other software uses for this.

Downloads into data/sources/raw/cldr/, skipping files already present. Kept separate from
fetch_sources.py's fetch_all() for the same reason fetch_vocabulary_sources.py is — a few
hundred small files nothing else needs.

`_BASE_LOCALES` is CLDR's "full" availableLocales list (cldr-core/availableLocales.json, 657
locales as of this writing) filtered down to locales with no REGION subtag — a language code
alone, or a language+SCRIPT subtag (e.g. "zh-Hans"/"zh-Hant", "sr-Cyrl"/"sr-Latn") — verified
live against unicode-org/cldr-json's main branch, 2026-11-19. Region variants (e.g. "ar-EG")
essentially never override exemplarCharacters from their base language locale, so there's
nothing to gain fetching the other ~370 of them. Script-subtag variants are fetched too even
though cldr_loader.py doesn't map them to anything yet (see its docstring) — having the data
already cached costs nothing and saves a re-fetch if that matching is ever added.
"""

